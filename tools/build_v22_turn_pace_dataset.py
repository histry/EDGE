#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build weakly supervised V22 turn-pace reconstruction data.

Natural continuous Dunhuang motion windows are targets.  Inputs are generated by
compressing the detected turn inside the same fixed-length window while keeping
window length and endpoints unchanged.  The model therefore learns to undo the
exact failure seen after phrase scheduling: a turn that completes too quickly.
"""
from __future__ import annotations

import argparse
import glob
import json
from pathlib import Path
from typing import Dict, List, Sequence, Set, Tuple

import numpy as np

from tools.v21_common import load_json_items, load_motion
from tools.v22_turn_utils import (
    detect_turn_events,
    make_fast_turn_corruption,
    motion_query_from_dynamics,
    summarize_turns,
    yaw_speed_dps_np,
)


def collect_sources(motion_globs: Sequence[str], event_db: str) -> List[Path]:
    paths: Set[Path] = set()
    for pattern in motion_globs:
        for value in glob.glob(pattern, recursive=True):
            p = Path(value)
            if p.is_file() and p.suffix.lower() in {".npy", ".npz", ".pkl"}:
                paths.add(p.resolve())
    if event_db:
        _, items = load_json_items(event_db)
        for item in items:
            for key in ("source_file", "source_path", "source", "pkl", "path"):
                value = str(item.get(key, "")).strip()
                if value:
                    p = Path(value)
                    if p.is_file():
                        paths.add(p.resolve())
                        break
    return sorted(paths)


def extract_window(motion: np.ndarray, center: int, window_len: int) -> Tuple[np.ndarray, int, int]:
    half = window_len // 2
    start = int(center - half)
    end = start + window_len
    if start < 0:
        start = 0
        end = window_len
    if end > len(motion):
        end = len(motion)
        start = max(0, end - window_len)
    window = motion[start:end]
    if len(window) < window_len:
        if len(window) == 0:
            raise ValueError("Empty motion window")
        pad = np.repeat(window[-1:], window_len - len(window), axis=0)
        window = np.concatenate([window, pad], axis=0)
    return window.astype(np.float32), int(start), int(end)


def build_condition(
    target: np.ndarray,
    corrupted: np.ndarray,
    target_peak_dps: float,
    corrupted_peak_dps: float,
    turn_angle_deg: float,
    speed_factor: float,
    turn_center_phase: float,
) -> np.ndarray:
    query = motion_query_from_dynamics(target)
    extra = np.asarray(
        [
            float(corrupted_peak_dps),
            float(target_peak_dps),
            float(turn_angle_deg),
            float(speed_factor),
            float(turn_center_phase),
        ],
        dtype=np.float32,
    )
    return np.concatenate([query, extra], axis=0).astype(np.float32)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--motion_glob", action="append", default=[])
    ap.add_argument("--event_db", default="")
    ap.add_argument("--out", required=True)
    ap.add_argument("--window_len", type=int, default=72)
    ap.add_argument("--fps", type=float, default=30.0)
    ap.add_argument("--min_peak_dps", type=float, default=38.0)
    ap.add_argument("--min_turn_angle_deg", type=float, default=18.0)
    ap.add_argument("--min_gap", type=int, default=24)
    ap.add_argument("--max_events_per_source", type=int, default=160)
    ap.add_argument("--augmentations_per_event", type=int, default=3)
    ap.add_argument("--min_speed_factor", type=float, default=1.30)
    ap.add_argument("--max_speed_factor", type=float, default=2.35)
    ap.add_argument("--identity_ratio", type=float, default=0.12)
    ap.add_argument("--max_samples", type=int, default=12000)
    ap.add_argument("--seed", type=int, default=20260605)
    args = ap.parse_args()

    if not args.motion_glob and not args.event_db:
        raise RuntimeError("Provide --motion_glob and/or --event_db")
    if args.window_len < 32:
        raise ValueError("window_len must be at least 32")

    sources = collect_sources(args.motion_glob, args.event_db)
    if not sources:
        raise RuntimeError("No source motions found")
    print("source motions:", len(sources))

    rng = np.random.default_rng(args.seed)
    corrupted_list: List[np.ndarray] = []
    target_list: List[np.ndarray] = []
    mask_list: List[np.ndarray] = []
    condition_list: List[np.ndarray] = []
    source_id_list: List[int] = []
    target_peak_list: List[float] = []
    corrupted_peak_list: List[float] = []
    factor_list: List[float] = []
    angle_list: List[float] = []
    metadata: List[Dict[str, object]] = []
    failed = 0

    for source_id, path in enumerate(sources):
        try:
            motion = load_motion(path)
        except Exception as exc:
            failed += 1
            print(f"[SKIP SOURCE] {path}: {exc}", flush=True)
            continue
        if len(motion) < args.window_len:
            continue

        events = detect_turn_events(
            motion,
            fps=args.fps,
            min_peak_dps=args.min_peak_dps,
            threshold_ratio=0.30,
            min_gap=args.min_gap,
            min_duration=4,
            max_events=args.max_events_per_source,
        )
        events = [event for event in events if event.path_angle_deg >= args.min_turn_angle_deg]
        if not events:
            continue

        for event_index, event in enumerate(events):
            target, window_start, _ = extract_window(motion, event.peak_index, args.window_len)
            local_start = int(np.clip(event.start - window_start, 1, args.window_len - 4))
            local_end = int(np.clip(event.end - window_start, local_start + 2, args.window_len - 2))
            target_speed = yaw_speed_dps_np(target, fps=args.fps)
            target_peak = float(target_speed.max()) if len(target_speed) else float(event.peak_speed_dps)
            turn_center_phase = float(0.5 * (local_start + local_end) / max(args.window_len - 1, 1))

            factors = rng.uniform(
                args.min_speed_factor,
                args.max_speed_factor,
                size=max(1, args.augmentations_per_event),
            ).tolist()
            if rng.random() < args.identity_ratio:
                factors.append(1.0)

            for factor in factors:
                if factor <= 1.001:
                    corrupted = target.copy()
                    mask = np.zeros((args.window_len,), dtype=np.float32)
                    center = int(round(0.5 * (local_start + local_end)))
                    radius = max(6, (local_end - local_start) // 2 + 5)
                    lo = max(0, center - radius)
                    hi = min(args.window_len - 1, center + radius)
                    phase = np.linspace(0.0, 1.0, hi - lo + 1, dtype=np.float32)
                    mask[lo : hi + 1] = np.sin(np.pi * phase) ** 2
                    corruption_info = {
                        "effective_speed_factor": 1.0,
                        "corrupted_turn_start": local_start,
                        "corrupted_turn_end": local_end,
                    }
                else:
                    corrupted, mask, corruption_info = make_fast_turn_corruption(
                        target,
                        local_start,
                        local_end,
                        speed_factor=float(factor),
                        min_context_frames=5,
                    )

                corrupted_speed = yaw_speed_dps_np(corrupted, fps=args.fps)
                corrupted_peak = float(corrupted_speed.max()) if len(corrupted_speed) else target_peak
                effective_factor = float(corruption_info.get("effective_speed_factor", factor))
                condition = build_condition(
                    target,
                    corrupted,
                    target_peak_dps=target_peak,
                    corrupted_peak_dps=corrupted_peak,
                    turn_angle_deg=event.path_angle_deg,
                    speed_factor=effective_factor,
                    turn_center_phase=turn_center_phase,
                )

                corrupted_list.append(corrupted.astype(np.float32))
                target_list.append(target.astype(np.float32))
                mask_list.append(mask.astype(np.float32))
                condition_list.append(condition)
                source_id_list.append(source_id)
                target_peak_list.append(target_peak)
                corrupted_peak_list.append(corrupted_peak)
                factor_list.append(effective_factor)
                angle_list.append(float(event.path_angle_deg))
                metadata.append(
                    {
                        "source": str(path),
                        "source_id": int(source_id),
                        "event_index": int(event_index),
                        "window_start": int(window_start),
                        "peak_frame": int(event.peak_index),
                        "turn_start": int(local_start),
                        "turn_end": int(local_end),
                        "target_peak_dps": float(target_peak),
                        "corrupted_peak_dps": float(corrupted_peak),
                        "turn_angle_deg": float(event.path_angle_deg),
                        "speed_factor": float(effective_factor),
                    }
                )
                if len(corrupted_list) >= args.max_samples:
                    break
            if len(corrupted_list) >= args.max_samples:
                break
        print(
            f"[{source_id + 1}/{len(sources)}] {path.name}: turns={len(events)} samples={len(corrupted_list)}",
            flush=True,
        )
        if len(corrupted_list) >= args.max_samples:
            break

    if not corrupted_list:
        raise RuntimeError("No turn-pace samples were built. Lower --min_peak_dps or verify root rotations.")

    condition_raw = np.stack(condition_list).astype(np.float32)
    condition_lo = np.percentile(condition_raw, 5, axis=0).astype(np.float32)
    condition_hi = np.percentile(condition_raw, 95, axis=0).astype(np.float32)
    condition = np.clip((condition_raw - condition_lo) / (condition_hi - condition_lo + 1e-8), 0.0, 1.0)

    order = rng.permutation(len(corrupted_list))
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(
        out,
        corrupted=np.stack(corrupted_list)[order].astype(np.float32),
        target=np.stack(target_list)[order].astype(np.float32),
        edit_mask=np.stack(mask_list)[order].astype(np.float32),
        condition=condition[order].astype(np.float32),
        condition_raw=condition_raw[order].astype(np.float32),
        condition_lo=condition_lo,
        condition_hi=condition_hi,
        source_id=np.asarray(source_id_list, dtype=np.int32)[order],
        target_peak_dps=np.asarray(target_peak_list, dtype=np.float32)[order],
        corrupted_peak_dps=np.asarray(corrupted_peak_list, dtype=np.float32)[order],
        speed_factor=np.asarray(factor_list, dtype=np.float32)[order],
        turn_angle_deg=np.asarray(angle_list, dtype=np.float32)[order],
    )
    metadata_path = out.with_suffix(".metadata.json")
    metadata_path.write_text(
        json.dumps(
            {
                "version": "v22_turn_pace_dataset",
                "sources": [str(path) for path in sources],
                "num_sources": len(sources),
                "failed_sources": failed,
                "num_samples": len(corrupted_list),
                "window_len": args.window_len,
                "fps": args.fps,
                "condition_dims": [
                    "energy", "upper", "torso", "lower", "tension", "calmness",
                    "support", "build_up", "release", "accent", "phrase_change", "duration",
                    "corrupted_peak_dps", "target_peak_dps", "turn_angle_deg",
                    "speed_factor", "turn_center_phase",
                ],
                "samples": [metadata[i] for i in order.tolist()],
            },
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )

    print("=" * 72)
    print("saved:", out)
    print("metadata:", metadata_path)
    print("samples:", len(corrupted_list))
    print("sources:", len(set(source_id_list)))
    print("speed factor p10/p50/p90:", np.percentile(np.asarray(factor_list), [10, 50, 90]))
    print("target peak p10/p50/p90:", np.percentile(np.asarray(target_peak_list), [10, 50, 90]))
    print("corrupt peak p10/p50/p90:", np.percentile(np.asarray(corrupted_peak_list), [10, 50, 90]))


if __name__ == "__main__":
    main()
